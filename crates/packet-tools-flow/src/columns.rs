use crate::Policy;

/// Logical type of a flows-table column.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ColumnType {
    /// UTF-8 string.
    Utf8,
    /// Unsigned 64-bit integer.
    UInt64,
    /// Signed 64-bit integer.
    Int64,
    /// IEEE 754 double-precision number.
    Float64,
}

/// A stable snake_case name and its CICFlowMeter spelling.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Column {
    /// Stable packet-tools name.
    pub snake: &'static str,
    /// CICFlowMeter CSV header.
    pub original: &'static str,
    /// Logical Arrow/Parquet type.
    pub data_type: ColumnType,
}

macro_rules! c {
    ($snake:literal, $original:literal, $kind:ident) => {
        Column {
            snake: $snake,
            original: $original,
            data_type: ColumnType::$kind,
        }
    };
}

